"""Fixed Hindi (Roman script) and English message templates.

Placeholder discipline: only fields from heatcore.daily.build_daily_plan fill
these templates. No number here is ever generated by an LLM.
"""

from datetime import datetime


def clock(hour: int) -> str:
    """24h hour -> spoken 12h number ('15' -> '3')."""
    h = hour % 12
    return str(12 if h == 0 else h)


def part_of_day(hour: int) -> str:
    if hour < 12:
        return "subah"
    if hour < 16:
        return "dopahar"
    return "shaam"


def when(hour: int) -> str:
    return f"{part_of_day(hour)} {clock(hour)} baje"


def forecast_line(plan: dict) -> str:
    issued = datetime.fromisoformat(plan["forecast_issued"])
    line = f"Forecast: {plan['forecast_model']}, {issued:%d %b %H:%M} IST."
    if plan.get("stale"):
        line += " Purana forecast hai, isliye plan zyada sakht rakha hai."
    return line
