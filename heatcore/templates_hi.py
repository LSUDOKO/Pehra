"""Fixed Hindi (Roman script) and English message templates.

Placeholder discipline: only fields from heatcore.daily.build_daily_plan fill
these templates. No number here is ever generated by an LLM.
"""

from datetime import datetime


def clock(hour: int) -> str:
    """24h hour -> spoken 12h number ('15' -> '3')."""
    h = hour % 12
    return str(12 if h == 0 else h)


def part_of_day(hour: int) -> str:
    if hour < 12:
        return "subah"
    if hour < 16:
        return "dopahar"
    return "shaam"


def when(hour: int) -> str:
    return f"{part_of_day(hour)} {clock(hour)} baje"


def forecast_line(plan: dict) -> str:
    issued = datetime.fromisoformat(plan["forecast_issued"])
    line = f"Forecast: {plan['forecast_model']}, {issued:%d %b %H:%M} IST."
    if plan.get("stale"):
        line += " Purana forecast hai, isliye plan zyada sakht rakha hai."
    return line


def rest_summary_hi(plan: dict) -> list[str]:
    lines = []
    for p in plan["rest_summary"]:
        span = f"{clock(p['from'])} se {clock(p['to'])} baje"
        if p["rest_minutes"] == 0:
            continue
        if p["rest_minutes"] == 60:
            lines.append(f"{span}: kaam band.")
        else:
            lines.append(f"{span}: har ghante {p['rest_minutes']} minute aaram.")
    return lines or ["Aaj koi zaroori aaram nahi. Phir bhi paani peete raho."]


def render_plan_hi(plan: dict) -> str:
    """The fallback plan message. Always works, no AI involved."""
    d = datetime.fromisoformat(plan["date"])
    out = [f"Kal ka plan ({plan['site_name']}, {d:%d %b}):"]
    if plan["stop_from"] is not None:
        out.append(f"- Kaam band: {when(plan['stop_from'])} se {when(plan['stop_to'])} tak.")
    else:
        out.append("- Pura din kaam band karne ki zaroorat nahi.")
    out += [f"- {line}" for line in rest_summary_hi(plan)]
    hs = plan.get("heavy_stop")
    if hs and hs["from"] is not None:
        out.append(f"- Bhaari kaam band: {clock(hs['from'])} se {clock(hs['to'])} baje tak.")
    nw = plan.get("new_workers")
    if nw:
        pct = round(nw["fraction"] * 100)
        out.append(f"- Naye mazdoor ({nw['count']}): aaj normal ka sirf {pct} pratishat kaam. "
                   f"Yeh unka din {nw['day']} hai.")
    out.append(f"- Paani: {plan['water']['cans_20l']} bade can (20 litre).")
    out.append(forecast_line(plan))
    return "\n".join(out)


